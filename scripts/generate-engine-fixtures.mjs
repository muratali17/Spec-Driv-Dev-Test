// Generates tests/fixtures/engine-moves.ts by running the pinned Stockfish engine
// under Node over the curated black-to-move FENs. This is development/build-time
// test tooling only; it never participates in browser gameplay (research R3, C1).
//
// Protocol per FEN (research R2):
//   ucinewgame
//   setoption name Clear Hash value true
//   position fen <FEN>
//   go depth <N>
//   ... await "bestmove <uci>" ...
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const { TIER_DEPTH } = await import(resolve(root, "src/engine/difficulty.ts"));
const { parseUci } = await import(resolve(root, "src/engine/uci.ts"));
const {
  ENGINE_POSITIONS,
  blackToMoveFenFor,
} = await import(resolve(root, "tests/fixtures/positions.ts"));

const initEngine = require("stockfish");

function createEngineDriver(engine) {
  let buffer = "";
  const waiters = [];

  engine.listener = (line) => {
    buffer += `${line}\n`;
    // Notify every waiter; each decides whether its pattern already arrived.
    for (const waiter of [...waiters]) waiter();
  };

  function waitFor(pattern, timeoutMs = 120_000) {
    return new Promise((resolvePromise, reject) => {
      const deadline = Date.now() + timeoutMs;
      const check = () => {
        const match = buffer.match(pattern);
        if (match) {
          buffer = buffer.slice(match.index + match[0].length);
          const index = waiters.indexOf(check);
          if (index >= 0) waiters.splice(index, 1);
          resolvePromise(match);
          return;
        }
        if (Date.now() > deadline) {
          const index = waiters.indexOf(check);
          if (index >= 0) waiters.splice(index, 1);
          reject(new Error(`Timed out waiting for ${pattern}`));
        }
      };
      waiters.push(check);
      check();
    });
  }

  return { waitFor };
}

async function searchMove(engine, driver, fen, depth) {
  const bestmove = driver.waitFor(/bestmove\s+(\S+)/);
  engine.sendCommand("ucinewgame");
  engine.sendCommand("setoption name Clear Hash value true");
  engine.sendCommand(`position fen ${fen}`);
  engine.sendCommand(`go depth ${depth}`);
  const [, move] = await bestmove;
  return move;
}

const engine = await initEngine("lite-single");
const driver = createEngineDriver(engine);

engine.sendCommand("uci");
await driver.waitFor(/uciok/);
engine.sendCommand("isready");
await driver.waitFor(/readyok/);

const entries = [];
for (const position of ENGINE_POSITIONS) {
  const fen = blackToMoveFenFor(position);
  const moves = {};
  for (const [difficulty, depth] of Object.entries(TIER_DEPTH)) {
    const best = await searchMove(engine, driver, fen, depth);
    moves[difficulty] = best === "(none)" || parseUci(best) === null ? null : best;
    console.log(`${position.id} [${difficulty}] depth=${depth} -> ${best}`);
  }
  entries.push({ id: position.id, fen, moves });
}

engine.sendCommand("quit");

const serialized = `// AUTO-GENERATED by scripts/generate-engine-fixtures.mjs. Do not edit by hand.
// Regenerate with: npm run generate:engine-fixtures
// Expected Stockfish replies (UCI) for the curated black-to-move positions per
// difficulty tier. See specs/001-chess-vs-computer/research.md (R3).

import type { Difficulty } from "../../src/game/types";

export interface EngineMoveFixture {
  id: string;
  fen: string;
  moves: Record<Difficulty, string | null>;
}

export const ENGINE_MOVES: EngineMoveFixture[] = ${JSON.stringify(entries, null, 2)};

export function expectedEngineMove(id: string, difficulty: Difficulty): string | null {
  const entry = ENGINE_MOVES.find((item) => item.id === id);
  if (!entry) throw new Error(\`No engine fixture for position "\${id}"\`);
  return entry.moves[difficulty];
}
`;

const outPath = resolve(root, "tests/fixtures/engine-moves.ts");
await writeFile(outPath, serialized, "utf8");
console.log(`[generate-engine-fixtures] Wrote ${entries.length} fixtures to ${outPath}`);
